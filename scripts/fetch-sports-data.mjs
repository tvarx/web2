// Fetch the full sports catalogue (categories, muscles, headers, ALL exercises)
// from the new backend endpoints and emit typed-generated modules for the site.
//   GET /sports/overview                          — categories/muscles/headers + exercise slugs
//   GET /sports/exercises?page&items_per_page=100 — every exercise with description/steps/media
//   GET /sports/categories/{slug}  (muscles same) — rich detail pages + enriched related_exercises
//   GET /sports/exercises/{slug}   (best-effort)  — extra admin data (reps/sets/tips)
// Usage: node scripts/fetch-sports-data.mjs [--force]
import "dotenv/config";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const API_BASE = process.env.SPORTS_API_BASE || "https://api.tvarx.com";
const LIST_PAGE_SIZE = 100;
const DETAIL_BATCH = 10;
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.resolve(__dirname, "../src/generated");
const OUT_FILE = path.join(OUT_DIR, "sports-data.ts");
const INDEX_FILE = path.join(OUT_DIR, "exercises-index.ts");
const MENU_FILE = path.join(OUT_DIR, "sports-menu.ts");
const DETAILS_FILE = path.join(OUT_DIR, "exercises-details.ts");

async function fetchJson(url, label, timeoutMs = 60000) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), timeoutMs);
  try {
    const res = await fetch(url, { signal: ctrl.signal });
    if (!res.ok) throw new Error(`${label} failed: ${res.status} ${res.statusText} (${url})`);
    return await res.json();
  } finally {
    clearTimeout(timer);
  }
}

async function fetchInBatches(items, batchSize, fn) {
  const results = [];
  for (let i = 0; i < items.length; i += batchSize) {
    const batch = items.slice(i, i + batchSize);
    results.push(...(await Promise.all(batch.map(fn))));
  }
  return results;
}

const json = (obj) => JSON.stringify(obj);

function toTs(obj, name) {
  return `// AUTO-GENERATED by scripts/fetch-sports-data.mjs — do not edit manually.
export default ${json(obj)};
`;
}

/**
 * Normalize the media payload into the { male: { front: {image, video} } } shape
 * consumed by the site. Some endpoints wrap it under the exercise's content id:
 *   { "<content_id>": { male: {...}, female: {...} } }
 * unwrap that single entry when present.
 */
const MEDIA_VIEWS = [
  ["male", "front"],
  ["male", "side"],
  ["female", "front"],
  ["female", "side"],
];

/**
 * Normalize the CDN video path after the media migration. Older list payloads
 * use a slug-based path that returns 404, while the exercise endpoint exposes
 * the working content-id based path.
 */
function normalizeMedia(m, contentId) {
  if (!m || typeof m !== "object") return null;
  const keys = Object.keys(m);
  const media =
    keys.length === 1 &&
    /^[0-9a-f]{24}$/i.test(keys[0]) &&
    m[keys[0]] &&
    typeof m[keys[0]] === "object" &&
    (m[keys[0]].male || m[keys[0]].female)
      ? m[keys[0]]
      : m;

  if (contentId) {
    for (const [gender, angle] of MEDIA_VIEWS) {
      const video = media[gender]?.[angle]?.video;
      if (typeof video === "string" && video.includes("c689729.parspack.net/exercise_videos-unbranded/") /* legacy CDN path */) {
        media[gender][angle].video = `https://c689729.parspack.net/c689729/exercise_videos-unbranded/exercise_${contentId}_${gender}_${angle}.mp4`;
      }
    }
  }
  return media;
}

function bestMedia(ex) {
  const m = normalizeMedia(ex?.media, ex?.content_id);
  const pick = (g, a) => m?.[g]?.[a]?.image;
  return pick("male", "front") || pick("male", "side") || pick("female", "front") || pick("female", "side") || "";
}

function pickDesc(ex) {
  const d = ex?.description;
  return typeof d === "string" ? { en: d, fa: d } : d && (d.en || d.fa) ? d : null;
}

function pickSteps(ex) {
  const s = ex?.correct_steps;
  if (!s) return null;
  return { en: Array.isArray(s.en) ? s.en : [], fa: Array.isArray(s.fa) ? s.fa : [] };
}

/** Snapshot a list item into an index record stub (fields we keep from list endpoints). */
function recordFromListItem(ex) {
  return {
    id: ex.id,
    content_id: ex.content_id,
    slug: ex.slug && (ex.slug.en || ex.slug.fa) ? ex.slug : null,
    name: ex.name,
    difficulty: ex.difficulty ?? null,
    need_warmup: !!ex.need_warmup,
    tags: Array.isArray(ex.tags) ? ex.tags : [],
    category: ex.category ?? null,
    equipment_needed: ex.equipment_needed ?? null,
    description: pickDesc(ex),
    correct_steps: pickSteps(ex),
    media: normalizeMedia(ex.media ?? null, ex.content_id) ?? null,
    extra: ex.extra ?? null,
    poster: bestMedia(ex),
    categories: [],
    muscles: [],
  };
}

/** Enrich a stub with any extra fields present on a richer payload. */
function mergeInto(rec, payload) {
  if (!payload) return rec;
  if (payload.slug?.en && !rec.slug?.en) rec.slug = payload.slug;
  if (!rec.equipment_needed && payload.equipment_needed != null) rec.equipment_needed = payload.equipment_needed;
  if (!rec.description) rec.description = pickDesc(payload);
  if (!rec.correct_steps) rec.correct_steps = pickSteps(payload);
  const media = normalizeMedia(payload.media, payload.content_id ?? rec.content_id);
  if (media && Object.keys(media).length > 0) {
    // Prefer the detail endpoint: it contains the current CDN paths even when
    // the list/category payload still has legacy URLs.
    rec.media = media;
  }
  if (!rec.poster) rec.poster = bestMedia(rec);
  if (payload.extra && Object.keys(payload.extra).length > 0 && !rec.extra) rec.extra = payload.extra;
  return rec;
}

async function headStatus(url, timeoutMs = 20000) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), timeoutMs);
  try {
    const res = await fetch(url, { method: "HEAD", signal: ctrl.signal });
    return res.status;
  } catch {
    return null; // network error / timeout
  } finally {
    clearTimeout(timer);
  }
}

const isMissingStatus = (s) => s === 404 || s === 410;

/**
 * The API's media payload can reference CDN video files that do not exist
 * (missing uploads or files removed after a migration). Probe every unique
 * video URL once (HEAD, bounded concurrency) and drop the `video` keys whose
 * files are missing, keeping the poster images so exercises degrade to a
 * "video coming soon" state instead of a player that can never start.
 * When a whole directory 404s on a sample, everything under it is assumed
 * missing and skipped without individual requests.
 */
export async function dropMissingVideos(records, { concurrency = 16 } = {}) {
  const urlToRefs = new Map();
  for (const rec of records) {
    const media = rec.media ?? {};
    for (const [gender, angle] of MEDIA_VIEWS) {
      const variant = media[gender]?.[angle];
      const url = variant?.video;
      if (!url) continue;
      if (!urlToRefs.has(url)) urlToRefs.set(url, []);
      urlToRefs.get(url).push({ rec, gender, angle });
    }
  }
  const unique = [...urlToRefs.keys()];
  if (!unique.length) return { total: 0, unique: 0, missing: 0, kept: 0 };

  const dirOf = (u) => {
    try {
      const p = new URL(u);
      return `${p.hostname}${p.pathname.substring(0, p.pathname.lastIndexOf("/") + 1)}`;
    } catch {
      return "";
    }
  };

  // Cheap whole-directory check first: sample a few files per directory; if
  // they are all missing, the directory is gone and every URL in it is too.
  const byDir = new Map();
  for (const url of unique) {
    const dir = dirOf(url);
    if (!byDir.has(dir)) byDir.set(dir, []);
    byDir.get(dir).push(url);
  }
  const missing = new Set();
  const toCheck = [];
  for (const urls of byDir.values()) {
    const sample = urls.slice(0, 25);
    const statuses = await Promise.all(sample.map((u) => headStatus(u)));
    if (statuses.every(isMissingStatus)) {
      urls.forEach((u) => missing.add(u));
    } else {
      sample.forEach((u, i) => {
        if (isMissingStatus(statuses[i])) missing.add(u);
        else toCheck.push(u);
      });
      urls.slice(sample.length).forEach((u) => toCheck.push(u));
    }
  }

  // Full per-URL pass for anything still in doubt.
  let cursor = 0;
  const workers = Array.from({ length: concurrency }, async () => {
    while (cursor < toCheck.length) {
      const url = toCheck[cursor++];
      const status = await headStatus(url);
      if (isMissingStatus(status)) missing.add(url);
    }
  });
  await Promise.all(workers);

  /**
   * CDN files are named exercise_{content_id}_{gender}_{angle}.mp4, but stale
   * payloads may still reference the old named path |{content_id}_{gender}-
   * {slug}-{angle}.mp4|. For any missing URL matching that legacy pattern, try
   * the canonical path on the same CDN before giving up.
   */
  const canonicalVariant = (url) => {
    const m = /exercise_videos-unbranded\/([0-9a-f]{24})_(male|female)-.+(front|side)\.mp4$/.exec(url);
    return m
      ? `https://c689729.parspack.net/c689729/exercise_videos-unbranded/exercise_${m[1]}_${m[2]}_${m[3]}.mp4`
      : null;
  };

  let removed = 0;
  let restored = 0;
  for (const url of missing) {
    const refs = urlToRefs.get(url) ?? [];
    const canonical = canonicalVariant(url);
    let replaced = false;
    if (canonical && !urlToRefs.has(canonical) && !isMissingStatus(await headStatus(canonical))) {
      for (const { rec, gender, angle } of refs) {
        const view = rec.media?.[gender]?.[angle];
        if (view?.video === url) {
          view.video = canonical;
          replaced = true;
        }
      }
      if (replaced) restored++;
    }
    if (!replaced) {
      for (const { rec, gender, angle } of refs) {
        const view = rec.media?.[gender]?.[angle];
        if (view?.video === url) {
          delete view.video;
          removed++;
        }
      }
    }
  }
  return {
    total: unique.length,
    unique: unique.length,
    missing: missing.size,
    restored,
    kept: unique.length - missing.size + restored,
    removed,
  };
}

async function main() {
  const started = Date.now();

  if (fs.existsSync(OUT_FILE) && !process.argv.includes("--force")) {
    const kb = (fs.statSync(OUT_FILE).size / 1024).toFixed(1);
    console.log(`sports data already present (${kb} KB). Use --force to refresh from ${API_BASE}.`);
    return;
  }

  console.log(`Fetching sports data from ${API_BASE} (list page size ${LIST_PAGE_SIZE}) ...`);

  const overview = await fetchJson(`${API_BASE}/sports/overview`, "GET /sports/overview", 120000);
  const { categories, muscles, headers } = overview;

  const categoryDetails = await fetchInBatches(categories, 6, async (c) => {
    try {
      const detail = await fetchJson(
        `${API_BASE}/sports/categories/${encodeURIComponent(c.slug.en)}?exercises_limit=30`,
        `GET /sports/categories/${c.slug.en}`
      );
      return [c.slug.en, detail];
    } catch (err) {
      console.warn(`skip category ${c.slug.en}: ${err.message}`);
      return [c.slug.en, null];
    }
  });
  const categoryDetailsMap = Object.fromEntries(categoryDetails.filter(([, v]) => v));

  const muscleDetails = await fetchInBatches(muscles, 6, async (m) => {
    try {
      const detail = await fetchJson(
        `${API_BASE}/sports/muscles/${encodeURIComponent(m.slug.en)}?exercises_limit=30`,
        `GET /sports/muscles/${m.slug.en}`
      );
      return [m.slug.en, detail];
    } catch (err) {
      console.warn(`skip muscle ${m.slug.en}: ${err.message}`);
      return [m.slug.en, null];
    }
  });
  const muscleDetailsMap = Object.fromEntries(muscleDetails.filter(([, v]) => v));

  // Full catalogue via the paginated public list (fast, complete).
  const listRecord = await fetchJson(
    `${API_BASE}/sports/exercises?page=1&items_per_page=${LIST_PAGE_SIZE}`,
    "GET /sports/exercises"
  );
  const total = listRecord.total ?? 0;
  const totalPages = Math.max(1, Math.ceil(total / LIST_PAGE_SIZE));
  const listItems = [...(listRecord.items ?? [])];
  for (let p = 2; p <= totalPages; p++) {
    const page = await fetchJson(
      `${API_BASE}/sports/exercises?page=${p}&items_per_page=${LIST_PAGE_SIZE}`,
      `GET /sports/exercises page ${p}/${totalPages}`
    );
    listItems.push(...(page.items ?? []));
  }
  console.log(`catalogue list: ${listItems.length}/${total} exercises`);

  // Deduplicated exercise index across list + category/muscle details.
  const byId = new Map();
  const upsert = (ex) => {
    const id = ex?.id || ex?.content_id;
    if (!id) return null;
    let rec = byId.get(id);
    if (!rec) rec = byId.set(id, (rec = recordFromListItem(ex))).get(id);
    else mergeInto(rec, ex);
    return rec;
  };

  for (const ex of listItems) upsert(ex);

  for (const c of categories) {
    const detail = categoryDetailsMap[c.slug.en];
    if (!detail?.related_exercises) continue;
    for (const ex of detail.related_exercises) {
      const rec = upsert(ex);
      if (rec && !rec.categories?.some((x) => x.en === c.slug.en)) {
        rec.categories = rec.categories ?? [];
        rec.categories.push({ en: c.slug.en, fa: c.slug.fa });
      }
    }
  }
  for (const m of muscles) {
    const detail = muscleDetailsMap[m.slug.en];
    if (!detail?.related_exercises) continue;
    for (const ex of detail.related_exercises) {
      const rec = upsert(ex);
      if (rec && !rec.muscles?.some((x) => x.en === m.slug.en)) {
        rec.muscles = rec.muscles ?? [];
        rec.muscles.push({ en: m.slug.en, fa: m.slug.fa });
      }
    }
  }

  // Fetch each exercise's detail page: this is the ONLY source of video media,
  // posters and (when present) `extra` admin data (reps/sets/safety tips).
  // Enabled by default; disable with FETCH_DETAILS=0 to skip (index will have
  // no videos/images).
  let extras = 0;
  let extraFails = 0;
  let mediaGained = 0;
  const needDetail = [...byId.values()].filter((r) => !r.media || Object.keys(r.media).length === 0);
  if ((process.env.FETCH_DETAILS ?? "1") === "1" && needDetail.length > 0) {
    console.log(`  detail enrichment for ${needDetail.length} exercises without media ...`);
    for (let i = 0; i < needDetail.length; i += DETAIL_BATCH) {
      const batch = needDetail.slice(i, i + DETAIL_BATCH);
      const results = await Promise.allSettled(
        batch.map((r) =>
          fetchJson(
            `${API_BASE}/sports/exercises/${encodeURIComponent(r.slug?.en || r.id)}`,
            `GET /sports/exercises/${r.slug?.en || r.id}`,
            30000
          )
        )
      );
      results.forEach((res, j) => {
        if (res.status === "fulfilled") {
          const ex = res.value;
          if (ex) {
            const hadMedia = !!batch[j].media && Object.keys(batch[j].media).length > 0;
            mergeInto(batch[j], ex);
            if (!hadMedia && batch[j].media && Object.keys(batch[j].media).length > 0) mediaGained++;
          }
          if (ex?.extra && Object.keys(ex.extra).length > 0) {
            batch[j].extra = ex.extra;
            extras++;
          }
        } else {
          extraFails++;
        }
      });
      if ((i / DETAIL_BATCH) % 20 === 0) {
        console.log(`  detail enrichment ${i}/${needDetail.length} (media+${mediaGained} extra=${extras} fail=${extraFails})`);
      }
    }
    console.log(`detail enrichment done: ${mediaGained} gained media, ${extras} with extra, ${extraFails} failed`);
  } else {
    console.log(`detail enrichment skipped (set FETCH_DETAILS=1 to enable; ${needDetail.length} without media)`);
  }

  // Slug safety: backend slugs are unique; keep a local dedupe fallback just in case.
  const usedSlugs = new Set();
  for (const rec of byId.values()) {
    if (rec.slug?.en && !usedSlugs.has(rec.slug.en)) {
      usedSlugs.add(rec.slug.en);
      continue;
    }
    const base = rec.slug?.en || String(rec.name?.en || "exercise")
      .toLowerCase()
      .replace(/&/g, " and ")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "") || "exercise";
    let slug = base;
    let n = 2;
    while (usedSlugs.has(slug)) slug = `${base}-${n++}`;
    usedSlugs.add(slug);
    rec.slug = rec.slug ?? {};
    rec.slug.en = slug;
    if (!rec.slug.fa) rec.slug.fa = slug;
  }

  // Video sanity: the API may hand out media whose CDN files are missing.
  // Validate at build time (drop dead URLs, keep posters) so the shipped site
  // never embeds a player that cannot start. Disable with VALIDATE_VIDEOS=0.
  if ((process.env.VALIDATE_VIDEOS ?? "1") === "1") {
    const v = await dropMissingVideos([...byId.values()]);
    console.log(
      `video validation: ${v.unique} unique refs, ${v.missing} missing, ${v.removed} video links removed, ${v.kept} kept`
    );
  } else {
    console.log("video validation skipped (set VALIDATE_VIDEOS=1 to enable)");
  }

  const index = [...byId.values()].sort((a, b) => (a.name?.en ?? "").localeCompare(b.name?.en ?? ""));

  // Split heavy rich text out of the index: the browser only needs it on the
  // dedicated exercise page, so it ships in its own lazily-loaded module.
  const detailsById = {};
  for (const rec of index) {
    const d = {};
    if (rec.description) d.description = rec.description;
    if (rec.correct_steps) d.correct_steps = rec.correct_steps;
    if (rec.extra && Object.keys(rec.extra).length > 0) d.extra = rec.extra;
    if (Object.keys(d).length > 0) detailsById[rec.id] = d;
    delete rec.description;
    delete rec.correct_steps;
    delete rec.extra;
  }

  // Tiny navigation/menu payload (headers + category/muscle summaries).
  const pickCat = (c) => ({
    type: c.type,
    slug: c.slug,
    name: c.name,
    image: c.image,
    rank: c.rank,
    exercise_count: c.exercise_count,
    degree_of_difficulty: c.degree_of_difficulty,
    equipment_needed: c.equipment_needed,
  });
  const pickMuscle = (m) => ({
    type: m.type,
    slug: m.slug,
    name: m.name,
    image: m.image,
    rank: m.rank,
    exercise_count: m.exercise_count,
    degree_of_difficulty: m.degree_of_difficulty,
  });
  const menu = {
    fetched_at: new Date().toISOString(),
    source: API_BASE,
    headers: headers.map((h) => ({
      id: h.id,
      title: h.title,
      categories: (h.categories ?? []).map(pickCat),
    })),
    categories: categories.map(pickCat),
    muscles: muscles.map(pickMuscle),
  };

  const data = {
    fetched_at: new Date().toISOString(),
    source: API_BASE,
    headers,
    categories,
    category_details: categoryDetailsMap,
    muscles,
    muscle_details: muscleDetailsMap,
    exercises_total: total,
  };

  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(OUT_FILE, toTs(data, "sports-data"), "utf8");
  fs.writeFileSync(INDEX_FILE, toTs(index, "exercises-index"), "utf8");
  fs.writeFileSync(MENU_FILE, toTs(menu, "sports-menu"), "utf8");
  fs.writeFileSync(DETAILS_FILE, toTs(detailsById, "exercises-details"), "utf8");

  const sizeKb = (f) => (fs.statSync(f).size / 1024).toFixed(1);
  console.log(
    `Done in ${((Date.now() - started) / 1000).toFixed(1)}s — ${categories.length} categories, ` +
      `${muscles.length} muscles, ${headers.length} header groups, ${index.length} unique exercises → ` +
      `${OUT_FILE} (${sizeKb(OUT_FILE)} KB) + ${INDEX_FILE} (${sizeKb(INDEX_FILE)} KB) + ` +
      `${MENU_FILE} (${sizeKb(MENU_FILE)} KB) + ${DETAILS_FILE} (${sizeKb(DETAILS_FILE)} KB)`
  );
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}